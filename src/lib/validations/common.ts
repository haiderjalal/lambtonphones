import { z } from 'zod';

import { splitLines, stripControlCharacters } from '@/utils/text';

const cleanText = (value: string): string => stripControlCharacters(value).trim();

const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DIGITS_ONLY = /\D/g;

/**
 * Free text is cleaned (control characters removed, trimmed) before the length check, so the
 * limit applies to what is actually stored.
 */
export function requiredText(
  label: string,
  { min = 1, max = 255 }: { min?: number; max?: number } = {},
) {
  return z
    .string({ error: `${label} is required.` })
    .transform(cleanText)
    .pipe(
      z
        .string()
        .min(
          min,
          min === 1 ? `${label} is required.` : `${label} must be at least ${min} characters.`,
        )
        .max(max, `${label} must be ${max} characters or fewer.`),
    );
}

export function optionalText(label: string, max: number) {
  return z
    .string()
    .transform(cleanText)
    .pipe(z.string().max(max, `${label} must be ${max} characters or fewer.`));
}

export const slugSchema = z
  .string({ error: 'URL slug is required.' })
  .trim()
  .min(2, 'URL slug must be at least 2 characters.')
  .max(80, 'URL slug must be 80 characters or fewer.')
  .regex(
    SLUG_PATTERN,
    'Use lowercase letters, numbers and hyphens only, for example screen-protector.',
  );

export const emailSchema = z
  .string({ error: 'Email address is required.' })
  .trim()
  .max(254, 'Email address must be 254 characters or fewer.')
  .pipe(z.email({ error: 'Enter a valid email address.' }))
  .transform((value) => value.toLowerCase());

export const phoneSchema = z
  .string({ error: 'Phone number is required.' })
  .trim()
  .regex(/^\+?[0-9 ()-]{8,20}$/, 'Enter a valid phone number.')
  .refine((value) => {
    const digitCount = value.replace(DIGITS_ONLY, '').length;
    return digitCount >= 8 && digitCount <= 15;
  }, 'Enter a valid phone number.');

export const sortOrderSchema = z
  .string()
  .trim()
  .regex(/^-?\d{1,4}$/, 'Sort order must be a whole number.')
  .transform(Number);

/** Empty select values mean "no parent". Anything else must be a UUID. */
export const optionalUuidSchema = z
  .string()
  .trim()
  .transform((value) => (value === '' ? null : value))
  .pipe(z.uuid({ error: 'Choose a valid option.' }).nullable());

export function requiredUuid(message: string) {
  return z
    .string()
    .trim()
    .pipe(z.uuid({ error: message }));
}

export function optionalHttpsUrl(label: string) {
  return z
    .string()
    .trim()
    .max(300, `${label} must be 300 characters or fewer.`)
    .refine((value) => value === '' || isHttpsUrl(value), `${label} must start with https://.`)
    .transform((value) => (value === '' ? null : value));
}

/** Newline-separated input (textarea) to a list of trimmed, non-empty lines. */
export function multilineList(
  label: string,
  { maxItems, maxItemLength }: { maxItems: number; maxItemLength: number },
) {
  return z
    .string()
    .transform((value) => splitLines(stripControlCharacters(value)))
    .pipe(
      z
        .array(
          z
            .string()
            .max(
              maxItemLength,
              `Each ${label.toLowerCase()} line must be ${maxItemLength} characters or fewer.`,
            ),
        )
        .max(maxItems, `${label} can have at most ${maxItems} lines.`),
    );
}

/**
 * Media paths are generated by the upload service (products/<uuid>.<ext> or blog/<uuid>.<ext>).
 * Anything else is rejected, which blocks arbitrary or traversal paths.
 */
export const mediaPathSchema = z
  .string()
  .trim()
  .max(300)
  .nullable()
  .refine(
    (value) =>
      value === null ||
      value === '' ||
      /^(products|blog)\/[a-f0-9-]{36}\.(jpg|png|webp|avif)$/.test(value),
    'Upload a valid image before saving.',
  )
  .transform((value) => (value ? value : null));

function isHttpsUrl(value: string): boolean {
  try {
    return new URL(value).protocol === 'https:';
  } catch {
    return false;
  }
}
